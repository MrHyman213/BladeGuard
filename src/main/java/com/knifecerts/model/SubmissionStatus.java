package com.knifecerts.model;

/**
 * Статус заявки на сертификат.
 * 
 * Определяет текущее состояние заявки в процессе модерации:
 * - PENDING: Заявка ожидает проверки модератором
 * - APPROVED: Заявка одобрена модератором
 * - REJECTED: Заявка отклонена модератором
 * 
 * Требования: 5.2, 9.3, 10.3
 */
public enum SubmissionStatus {
    /**
     * Заявка ожидает проверки модератором.
     * Фото находится в папке offers/ на Yandex.Disk.
     */
    PENDING,
    
    /**
     * Заявка одобрена модератором.
     * Фото перемещено в папку certificates/ на Yandex.Disk.
     */
    APPROVED,
    
    /**
     * Заявка отклонена модератором.
     * Фото удалено с Yandex.Disk.
     */
    REJECTED
}
